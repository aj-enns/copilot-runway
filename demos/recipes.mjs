import { mdText, mdFence, mdUrl } from "../scripts/lib.mjs";
import { validateRecipe, runRecipe, sameRecipeOutput, featureSourceIds } from "../site/model.mjs";

export { validateRecipe, runRecipe, sameRecipeOutput };

export function recipeFeatures(features) {
  return features.filter((feature) => feature.demo && Object.hasOwn(feature.demo, "recipe"));
}

export function assertRecipeFeature(feature) {
  if (!/^[a-z0-9][a-z0-9-]{0,59}$/.test(feature.id)) throw new Error(`${feature.id}: unsafe recipe feature id`);
  validateRecipe(feature.demo.recipe);
  if (feature.demo.runbook !== `demos/${feature.id}/README.md`) throw new Error(`${feature.id}: recipe runbook must be demos/${feature.id}/README.md`);
  if (feature.demo.liveStatus !== "not-run") throw new Error(`${feature.id}: recipe demos cannot claim live validation`);
}

// Recipe features add to, and never replace, the bespoke registry.
export function recipeFixtures(features, bespoke = {}) {
  const result = {};
  for (const feature of recipeFeatures(features)) {
    assertRecipeFeature(feature);
    if (Object.hasOwn(bespoke, feature.id) || Object.hasOwn(result, feature.id)) throw new Error(`${feature.id}: duplicate demo fixture`);
    const { recipe } = feature.demo;
    result[feature.id] = { files: { ...recipe.files }, outputs: [recipe.output, `offline-${recipe.output}`], recipe };
  }
  return result;
}

export function recipeRunbook(feature, sources) {
  assertRecipeFeature(feature);
  const { demo } = feature;
  const { recipe } = demo;
  const md = mdText;
  const fence = mdFence;
  return `<!-- Generated by npm run artifacts from catalog/features.json. Do not edit. -->\n` +
    `# ${md(feature.name)}: ${md(demo.title)}\n\n` +
    `**${demo.minutes} minutes | ${md(demo.mode)} | Offline kit; live feature validation: ${demo.liveStatus}**\n\n` +
    `## Prepare locally\n\n\`\`\`powershell\nnpm run demo:setup -- ${feature.id}\nnpm run demo:rehearse -- ${feature.id}\n\`\`\`\n\n` +
    `The rehearsal writes \`offline-${recipe.output}\`, marked as an offline rehearsal. It cannot pass live verification.\n\n` +
    `## Present the live feature\n\n${fence(demo.prompt)}\n\n` +
    `${recipe.steps.map((step, index) => `${index + 1}. **${step.title}.** ${step.detail}`).join("\n")}\n\n` +
    `Expected outcome: ${md(demo.expected)}\n\n` +
    `## Verify and reset\n\n\`\`\`powershell\nnpm run demo:verify -- ${feature.id}\nnpm run demo:reset -- ${feature.id}\n\`\`\`\n\n` +
    `Verification checks \`${recipe.output}\` against the deterministic expected result only. Inspect live traces and remote state separately.\n\n` +
    `Remote cleanup: ${md(demo.remoteCleanup)}\n\n` +
    `## Official sources\n\n${featureSourceIds(feature).map((id) => `- ${mdUrl(sources[id].url)}`).join("\n")}\n`;
}

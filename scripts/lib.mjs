import { readFile, writeFile, mkdir, lstat } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { freshness, verdict, verdictLabels } from "../site/model.mjs";

export { freshness, verdict, verdictLabels };

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const fromRoot = (...parts) => resolve(root, ...parts);
export const readJson = async (path) => JSON.parse(await readFile(path, "utf8"));
export const readText = (path) => readFile(path, "utf8");

export async function write(path, content) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function loadCatalog() {
  const [catalog, sourceDocument, rubric, monitor] = await Promise.all([
    readJson(fromRoot("catalog", "features.json")),
    readJson(fromRoot("catalog", "sources.json")),
    readJson(fromRoot("readiness", "gates.json")),
    readJson(fromRoot("catalog", "monitor.json")),
  ]);
  return { ...catalog, sources: sourceDocument.sources, rubric, monitor };
}

export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

export function fingerprint(feature, data) {
  const sourceIds = [...new Set([
    feature.lifecycle.source,
    ...feature.cost.sources,
    ...feature.enablement.flatMap((step) => step.sources),
    ...feature.readiness.flatMap((gate) => gate.sources),
  ])].sort();
  return createHash("sha256").update(JSON.stringify({
    feature,
    rubric: data.rubric,
    sources: sourceIds.map((id) => [id, data.sources[id]]),
  })).digest("hex");
}

export function isOfficialUrl(value, allowedHosts) {
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password &&
      (!url.port || url.port === "443") && allowedHosts.includes(url.hostname);
  } catch {
    return false;
  }
}

export function isDate(value) {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return Number.isFinite(date.valueOf()) && date.toISOString().slice(0, 10) === value;
}

export function assessmentMarkdown(feature, data) {
  const result = verdict(feature, data.rubric, new Date(`${feature.verifiedOn}T12:00:00Z`), data.sources);
  const sourceIds = [...new Set([
    feature.lifecycle.source, ...feature.cost.sources,
    ...feature.enablement.flatMap((step) => step.sources),
    ...feature.readiness.flatMap((gate) => gate.sources),
  ])];
  const sourceLink = (id) => `[${data.sources[id].title}](${data.sources[id].url})`;
  const cell = (text) => text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  return `<!-- Generated by npm run artifacts. Edit catalog/features.json and readiness/gates.json. -->\n` +
    `# ${feature.name}: enterprise readiness\n\n` +
    `**${verdictLabels[result]}** | ${feature.lifecycle.status} | Verified ${feature.verifiedOn} | Rubric ${data.rubric.version}\n\n` +
    `${feature.summary}\n\n${feature.lifecycle.note}\n\n` +
    `This is a minimum assessment for a controlled pilot, not a production certification or customer-specific approval. ` +
    `Unknowns block adoption; conditions require named tenant evidence. Evidence older than ${data.rubric.reviewWindowDays} days is stale.\n\n` +
    `## Non-negotiable gates\n\n| Gate | Finding | Evidence and gap | Required next action |\n| --- | --- | --- | --- |\n` +
    feature.readiness.map((assessment) => {
      const gate = data.rubric.gates.find((candidate) => candidate.id === assessment.gate);
      return `| ${cell(gate.name)} | ${assessment.status} | ${cell(assessment.reason)} ${assessment.sources.map(sourceLink).join("; ")} | ${cell(assessment.next)} |`;
    }).join("\n") +
    `\n\n## Value and cost\n\n${feature.value.map((value) => `- ${value}`).join("\n")}\n\n` +
    `**${feature.cost.headline}**\n\n${feature.cost.detail}\n\n` +
    `Assumptions:\n${feature.cost.assumptions.map((assumption) => `- ${assumption}`).join("\n")}\n\n` +
    `## Enablement\n\n${feature.enablement.map((step, index) =>
      `${index + 1}. **${step.title}.** ${step.detail}${step.command ? `\n\n\`\`\`text\n${step.command}\n\`\`\`` : ""}`).join("\n\n")}\n\n` +
    `## Demo and artifacts\n\n` +
    `- [Presenter runbook](../../${feature.demo.runbook})\n` +
    `- [Two-slide feature brief](../../artifacts/slides/${feature.id}.pptx)\n` +
    `- Kit status: ${feature.demo.status}. Live feature validation: ${feature.demo.liveStatus}.\n` +
    `- Expected outcome: ${feature.demo.expected}\n` +
    `- Separate remote cleanup: ${feature.demo.remoteCleanup}\n\n` +
    `## Known limitations\n\n${feature.limitations.map((limit) => `- ${limit}`).join("\n")}\n\n` +
    `## Primary sources\n\n${sourceIds.map((id) => `- ${sourceLink(id)} (reviewed ${data.sources[id].verifiedOn})`).join("\n")}\n`;
}

export async function assertNoSymlink(path, boundary) {
  const base = resolve(boundary);
  const target = resolve(path);
  if (target !== base && !target.startsWith(`${base}${sep}`)) throw new Error(`Path escapes approved boundary: ${target}`);
  const components = target.slice(base.length).split(sep).filter(Boolean);
  let current = base;
  for (const component of ["", ...components]) {
    current = component ? resolve(current, component) : current;
    try {
      const stat = await lstat(current);
      if (stat.isSymbolicLink()) throw new Error(`Refusing symbolic link or junction: ${current}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
}
